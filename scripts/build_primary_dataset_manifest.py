"""
Build the inclusion manifest for PRIMARY-DATASET-v1 -- the authoritative
definition of the high-confidence benchmark. Does NOT copy/duplicate
sample text; the manifest lists which sample_ids from samples.jsonl are
included and why, so the benchmark is always generated by filtering the
one complete sample store, never by assuming every generated record is
valid (per explicit instruction).

Inclusion rules:
- human: always included (150) -- unmodified source text, no QC
  question applies.
- full_ai: included iff qc_status == "passed". The 2 samples flagged
  for genuine ai_self_reference ("As an AI language model...") are
  real contamination, not a borderline call, and are excluded.
- sentence_light_controlled_v2: included iff semantic_preservation ==
  "preserved" (mandatory human review is authoritative; automated
  screen label never overrides it -- DEC-012/DEC-011). This includes 6
  samples with qc_status == "flagged" (modification_scope_drift --
  a length-ratio notice, not a semantic judgment) whose meaning a
  human reviewer confirmed was preserved -- same precedent as
  EXP-DATA-001-R3. Samples with qc_status == "rejected" were never
  reviewable (unresolvable span) and are excluded by construction
  (semantic_preservation stays "not_yet_reviewed" for these).
  "questionable" and "changed" are excluded regardless of automated
  screen label, per explicit instruction.
"""

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASET_DIR = REPO_ROOT / "data" / "generated" / "PRIMARY-DATASET-v1"


def main() -> None:
    samples_path = DATASET_DIR / "samples.jsonl"
    records = [json.loads(line) for line in samples_path.read_text().splitlines() if line.strip()]

    included = []
    excluded = []

    for r in records:
        cat = r["transformation_type"]
        if cat == "original":
            included.append({"sample_id": r["sample_id"], "category": "human", "reason": "unmodified source text"})
        elif cat == "full_ai":
            if r["qc_status"] == "passed":
                included.append({"sample_id": r["sample_id"], "category": "full_ai", "reason": "qc_status=passed"})
            else:
                excluded.append({
                    "sample_id": r["sample_id"], "category": "full_ai",
                    "reason": f"qc_status={r['qc_status']}, qc_notes={r['qc_notes']}",
                })
        elif cat == "sentence_light_controlled_v2":
            sp = r.get("semantic_preservation")
            if sp == "preserved":
                included.append({
                    "sample_id": r["sample_id"], "category": "ai_assisted",
                    "reason": f"semantic_preservation=preserved, qc_status={r['qc_status']}",
                })
            else:
                excluded.append({
                    "sample_id": r["sample_id"], "category": "sentence_light_controlled_v2",
                    "reason": f"semantic_preservation={sp}, qc_status={r['qc_status']}",
                })

    manifest = {
        "dataset": "PRIMARY-DATASET-v1",
        "source_samples_file": str(samples_path.relative_to(REPO_ROOT)),
        "total_records_generated": len(records),
        "included_count": len(included),
        "excluded_count": len(excluded),
        "included": included,
        "excluded": excluded,
    }

    manifest_path = DATASET_DIR / "inclusion_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))
    print(f"Wrote manifest: {manifest_path}")
    print(f"Included: {len(included)} / Excluded: {len(excluded)} / Total: {len(records)}")

    from collections import Counter
    print("Included by category:", Counter(r["category"] for r in included))


if __name__ == "__main__":
    main()
